void i2c_bus_scan(void)
{
    printf("=== SKANOWANIE MAGISTRALI I2C ===\r\n");
    uint8_t found_count = 0;

    /* Adresy 7-bitowe od 0x01 do 0x7E (0x00 i 0x7F to adresy zarezerwowane) */
    for (uint8_t addr7 = 0x01; addr7 < 0x7F; addr7++)
    {
        uint8_t addr8 = addr7 << 1;   /* HAL wymaga adresu przesuniętego o 1 bit */

        /* HAL_I2C_IsDeviceReady wysyła sam adres i sprawdza ACK/NAK,
           bez wysyłania żadnych danych - idealne do skanowania */
        HAL_StatusTypeDef status = HAL_I2C_IsDeviceReady(&hi2c1, addr8, 2, 10);

        if (status == HAL_OK)
        {
            printf("Znaleziono urzadzenie: adres 7-bit = 0x%02X (8-bit = 0x%02X)\r\n",
                   addr7, addr8);
            found_count++;
        }

        HAL_Delay(2);   /* mały odstęp między próbami, dla stabilności magistrali */
    }

    printf("=== KONIEC SKANOWANIA - znaleziono %d urzadzen ===\r\n", found_count);
}

void i2c_bus_recovery(void)
{
    /* Tymczasowo przełącz PB6(SCL)/PB7(SDA) na zwykłe GPIO */
    GPIO_InitTypeDef gpio = {0};
    gpio.Mode = GPIO_MODE_OUTPUT_OD;   /* open-drain, tak jak prawdziwe I2C */
    gpio.Pull = GPIO_NOPULL;
    gpio.Speed = GPIO_SPEED_FREQ_LOW;

    gpio.Pin = GPIO_PIN_6;
    HAL_GPIO_Init(GPIOB, &gpio);   /* SCL jako GPIO */
    gpio.Pin = GPIO_PIN_7;
    HAL_GPIO_Init(GPIOB, &gpio);   /* SDA jako GPIO */

    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_7, GPIO_PIN_SET);   /* SDA wysoko */

    /* Wygeneruj do 9 impulsów zegara - tyle, ile maksymalnie bitów może "czekać" slave */
    for (int i = 0; i < 9; i++) {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_RESET);
        HAL_Delay(1);
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_SET);
        HAL_Delay(1);

        /* Jeśli SDA wróciło do stanu wysokiego, urządzenie się zwolniło - koniec */
        if (HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_7) == GPIO_PIN_SET) {
            break;
        }
    }

    /* Wygeneruj warunek STOP (SDA idzie w górę, gdy SCL jest wysoko) */
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_7, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_SET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_7, GPIO_PIN_SET);
    HAL_Delay(1);

    /* Przywróć piny do trybu I2C (Alternate Function) */
    MX_I2C1_Init();
}
